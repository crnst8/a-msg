// Vendors a small subset of Phosphor (MIT) into one generated module, so no icon package ships at runtime.
// Navigation icons are the supplied PNGs and never come from here. Run: node scripts/generate-symbols.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const base = fileURLToPath(new URL('../node_modules/@phosphor-icons/core/assets', import.meta.url))

// Space catalog: solid shapes that sit beside the supplied navigation glyphs.
const catalog = {
  thread: 'chats-circle', umbrella: 'umbrella', server: 'hard-drives', calendar: 'calendar-blank',
  newspaper: 'newspaper', clock: 'clock', flask: 'flask', leaf: 'leaf', moon: 'moon', sun: 'sun',
  bolt: 'lightning', globe: 'globe-hemisphere-west', house: 'house', mountains: 'mountains',
  airplane: 'airplane-tilt', briefcase: 'briefcase', book: 'book-open', music: 'music-notes',
  camera: 'camera', heart: 'heart', star: 'star', cart: 'shopping-cart', wallet: 'wallet',
  chart: 'chart-line-up', terminal: 'terminal-window', bug: 'bug', rocket: 'rocket', puzzle: 'puzzle-piece',
  compass: 'compass', mail: 'envelope-simple',
}
// Interface controls.
const controls = {
  send: ['paper-plane-right', 'fill'], stop: ['stop', 'fill'], attach: ['paperclip', 'bold'],
  close: ['x', 'bold'], check: ['check', 'bold'], more: ['dots-three', 'bold'], search: ['magnifying-glass', 'bold'],
  plus: ['plus', 'bold'], copy: ['copy', 'regular'], down: ['arrow-down', 'bold'], up: ['arrow-up', 'bold'],
  external: ['arrow-square-out', 'regular'], retry: ['arrow-clockwise', 'bold'], warning: ['warning', 'fill'],
  alert: ['warning-circle', 'fill'], success: ['check-circle', 'fill'], clockBadge: ['clock', 'fill'],
  file: ['file', 'fill'], fileText: ['file-text', 'fill'], fileImage: ['file-image', 'fill'],
  filePdf: ['file-pdf', 'fill'], fileAudio: ['file-audio', 'fill'], fileVideo: ['file-video', 'fill'],
  fileCode: ['file-code', 'fill'], fileZip: ['file-zip', 'fill'], download: ['download-simple', 'bold'],
  hide: ['eye-slash', 'regular'], show: ['eye', 'regular'], trash: ['trash', 'regular'],
  rename: ['pencil-simple', 'regular'], archive: ['archive', 'regular'], restore: ['arrow-counter-clockwise', 'bold'],
  fork: ['git-branch', 'regular'], pause: ['pause', 'fill'], play: ['play', 'fill'], folder: ['folder', 'fill'],
  menu: ['sidebar-simple', 'regular'], caret: ['caret-down', 'bold'], caretRight: ['caret-right', 'bold'],
  moveUp: ['arrow-line-up', 'regular'], moveDown: ['arrow-line-down', 'regular'], offline: ['cloud-slash', 'fill'],
  key: ['key', 'regular'], link: ['link-simple', 'bold'], moreV: ['dots-three-vertical', 'bold'],
  drag: ['dots-six-vertical', 'bold'], connection: ['plugs-connected', 'fill'], history: ['clock-counter-clockwise', 'regular'],
  undo: ['arrow-u-up-left', 'bold'], reveal: ['folder-open', 'regular'],
}

const read = (name, weight) => {
  const suffix = weight === 'regular' ? '' : `-${weight}`
  const svg = readFileSync(join(base, weight, `${name}${suffix}.svg`), 'utf8')
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).join(' ')
}
const output = {}
for (const [key, name] of Object.entries(catalog)) output[key] = read(name, 'fill')
for (const [key, [name, weight]] of Object.entries(controls)) output[key] = read(name, weight)

writeFileSync(
  new URL('../src/components/symbols.gen.ts', import.meta.url),
  `// Generated by scripts/generate-symbols.mjs from @phosphor-icons/core (MIT). Do not edit.\n` +
    `export const SYMBOLS = ${JSON.stringify(output, null, 0)} as const\n` +
    `export const CATALOG = ${JSON.stringify(Object.keys(catalog))} as const\n` +
    `export type SymbolName = keyof typeof SYMBOLS\n`,
)
