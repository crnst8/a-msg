test('a coding session chooses its access and changes it later', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: /^Code Connector/ }).click()
  const name = unique('Codex')
  await page.getByRole('button', { name: 'Add connection' }).first().click()
  await page.getByLabel('Name').fill(name)
  await page.getByLabel('Allowed folders, one per line').fill('/tmp')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('region', { name }).getByRole('button', { name: 'New session' }).click()
  const access = page.getByRole('radiogroup', { name: 'Access' })
  await expect(access.getByRole('radio')).toHaveText(['Read only', 'Workspace', 'Full access'])
  await expect(access.getByRole('radio', { name: 'Workspace' })).toHaveAttribute('aria-checked', 'true')
  await access.getByRole('radio', { name: 'Full access' }).click()
  const title = unique('Session')
  await page.getByLabel('Name').fill(title)
  await page.getByRole('button', { name: 'Start' }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  const status = page.locator('header [role="status"]')
  await expect(status).toContainText('Full access')
  await page.getByRole('button', { name: 'Space options' }).click()
  await expect(page.getByRole('menuitemradio', { name: 'Full access' })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('menuitemradio', { name: 'Workspace' }).click()
  await expect(status).not.toContainText('Full access')
  await page.getByRole('button', { name: 'Space options' }).click()
  await expect(page.getByRole('menuitemradio', { name: 'Workspace' })).toHaveAttribute('aria-checked', 'true')
})
