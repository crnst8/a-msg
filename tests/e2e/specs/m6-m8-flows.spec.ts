import { expect, test } from '@playwright/test'
import { article, composer, newSpace, open, send, unique } from './helpers'
import { writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('a thread created from a message keeps the source and links both ways', async ({ page }) => {
  await open(page)
  const title = unique('Source')
  await newSpace(page, title)
  await send(page, 'Plan the move')
  await expect(page.locator('article[data-role="agent"]')).toContainText('Received.')
  const user = page.locator('article[data-role="user"]')
  await user.hover()
  await user.getByRole('button', { name: 'More' }).click()
  await page.getByRole('menuitem', { name: 'Create thread from here' }).click()
  await expect(page.getByText('1 message selected')).toBeVisible()
  await page.locator('article[data-role="agent"]').getByRole('checkbox').click()
  await expect(page.getByText('2 messages selected')).toBeVisible()
  await page.getByRole('button', { name: 'Continue' }).click()
  const name = page.getByLabel('Name')
  await expect(name).toHaveValue('Plan the move')
  const threadTitle = unique('Plan the move')
  await name.fill(threadTitle)
  await page.getByRole('button', { name: 'Create' }).click()
  await expect(page.getByRole('heading', { name: threadTitle })).toBeVisible()
  await expect(page.locator('article[data-role="context"]')).toContainText('2 messages from')
  await page.locator('article[data-role="context"]').getByRole('button', { name: title }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await expect(page.getByText(`Continued in ${threadTitle}`).first()).toBeVisible()
  await expect(page.locator('article[data-role="user"]')).toHaveCount(1)
})

test('files stage without sending, then appear in chat and Library', async ({ page }) => {
  await open(page)
  await newSpace(page, unique('Files'))
  const name = `${unique('report').replace(' ', '-')}.txt`
  const path = join(tmpdir(), name)
  writeFileSync(path, 'Quarterly numbers\n')
  await page.locator('input[type=file]').first().setInputFiles(path)
  await expect(page.getByText(name)).toBeVisible()
  await expect(article(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('article[data-role="user"]').getByRole('button', { name, exact: true })).toBeVisible()
  await page.locator('article[data-role="user"]').getByRole('button', { name, exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Quarterly numbers')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /^Library/ }).click()
  await page.getByLabel('Search files').fill(name)
  await page.getByRole('listbox', { name: 'Files' }).getByRole('option', { name: new RegExp(name) }).click()
  await expect(page.getByRole('complementary').getByText('Quarterly numbers')).toBeVisible()
  await page.getByRole('button', { name: 'Hide' }).click()
  await expect(page.getByText('No matching files.')).toBeVisible()
})

test('an oversized or failed upload keeps the draft and offers per-file retry', async ({ page }) => {
  await open(page)
  await newSpace(page, unique('Upload error'))
  await composer(page).fill('keep this text')
  await page.route('**/api/v1/uploads', (route) => route.abort())
  const path = join(tmpdir(), 'broken.txt')
  writeFileSync(path, 'x')
  await page.locator('input[type=file]').first().setInputFiles(path)
  await expect(page.getByRole('button', { name: 'Retry broken.txt' })).toBeVisible()
  await expect(composer(page)).toHaveValue('keep this text')
  await page.unroute('**/api/v1/uploads')
  await page.getByRole('button', { name: 'Retry broken.txt' }).click()
  await expect(page.getByRole('button', { name: 'Retry broken.txt' })).toBeHidden()
  await composer(page).fill('')
  await page.getByRole('button', { name: 'Remove broken.txt' }).click()
})

test('dropping files shows an overlay and stages them', async ({ page }) => {
  await open(page)
  await newSpace(page, unique('Drop'))
  const view = page.locator('section').first()
  const data = await page.evaluateHandle(() => {
    const transfer = new DataTransfer()
    transfer.items.add(new File(['dropped'], 'dropped.txt', { type: 'text/plain' }))
    return transfer
  })
  await view.dispatchEvent('dragenter', { dataTransfer: data })
  await expect(page.getByText('Drop files to attach')).toBeVisible()
  await view.dispatchEvent('drop', { dataTransfer: data })
  await expect(page.getByText('Drop files to attach')).toBeHidden()
  await expect(page.getByText('dropped.txt')).toBeVisible()
  await expect(article(page)).toHaveCount(0)
})

